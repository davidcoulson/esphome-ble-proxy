#!/usr/bin/env bash
# Every board x variant must advertise an import target that exists and keeps the
# variant, so adopting a flashed `noapple-adv` does not rebuild as `standard`.
#
#   ./check.sh          verify (CI)
#   ./check.sh --write  (re)generate config/adopt/variants/*.yaml
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
adopt="$here/../config/adopt/variants"
repo=github://davidcoulson/esphome-ble-proxy
mkdir -p "$adopt"
fail=0
for b in "$here"/*.yaml; do
  board="$(basename "$b" .yaml)"
  [[ "$board" == _build ]] && continue
  for v in "$here"/variants/*.yaml; do
    variant="$(basename "$v" .yaml)"
    # compose.sh only overrides dashboard_import for non-standard variants; the
    # board file's own url is what the standard build advertises.
    url="$( { cat "$b"; "$here/compose.sh" "$board" "$variant"; } | sed -n 's/^ *package_import_url: //p' | tail -1)"
    if [[ "$variant" == standard ]]; then
      # Board-only target is equivalent: standard is what the board package builds.
      [[ -f "$here/../config/adopt/$board.yaml" ]] || { echo "FAIL $board/$variant: no adopt file" >&2; fail=1; }
      [[ "$url" == "$repo/config/adopt/$board.yaml@main" ]] || { echo "FAIL $board/$variant: url $url" >&2; fail=1; }
      continue
    fi
    f="$adopt/$board--$variant.yaml"
    [[ "$url" == "$repo/config/adopt/variants/$board--$variant.yaml@main" ]] \
      || { echo "FAIL $board/$variant: url $url" >&2; fail=1; }
    body="# GENERATED by firmware/check.sh --write - do not edit.
# Adoption target for $board / $variant: the board package plus the variant, so
# an adopted device keeps the build it was flashed as.
packages:
  board: $repo/config/adopt/$board.yaml@main
  variant: $repo/firmware/variants/$variant.yaml@main"
    if [[ "${1:-}" == --write ]]; then
      printf '%s\n' "$body" > "$f"
    else
      [[ -f "$f" && "$(cat "$f")" == "$body" ]] || { echo "FAIL $board/$variant: $f missing or stale" >&2; fail=1; }
    fi
  done
done
exit $fail
